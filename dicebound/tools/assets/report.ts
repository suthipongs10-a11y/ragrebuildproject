import { existsSync, readFileSync } from 'node:fs';
import { CONFIG } from './config';
import type { PackListing } from './manifest';
import type { EntryResult } from './process';

const tick = (ok: boolean): string => (ok ? 'ok' : '**CHECK**');

export function buildReport(listings: PackListing[], results: EntryResult[], notesPath: string, totals: { frames: number; images: number; atlasPages: number }): string {
  const lines: string[] = [];
  lines.push('# ASSET REPORT — DICEBOUND', '');
  lines.push('> Generated by `npm run assets`. Do not edit — hand-written review notes live in `tools/assets/review-notes.md` and are appended below.', '');
  lines.push(`Resize: **${CONFIG.resizeKernel}** · output: ${totals.frames} frames in ${totals.atlasPages} atlas pages + ${totals.images} standalone images`, '');

  lines.push('## 1. raw/ vs manifest', '', '| Pack | In manifest | Found | Missing | Not in manifest |', '|---|---|---|---|---|');
  for (const listing of listings) {
    const missing = listing.entries.filter((e) => !e.exists).map((e) => e.file);
    lines.push(
      `| ${listing.pack} | ${listing.manifestFound ? listing.entries.length : '**no manifest.csv**'} | ${listing.entries.length - missing.length} | ${missing.join(', ') || '-'} | ${listing.unlisted.join(', ') || '-'} |`,
    );
  }

  const problems = results.filter((r) => r.status === 'failed' || r.status === 'missing');
  lines.push('', '## 2. Needs a new image', '');
  if (problems.length === 0) lines.push('Nothing: every sheet was cut into the number of pieces its manifest expects.');
  else {
    lines.push('These use a magenta placeholder in the game until replaced.', '', '| File | Problem | Regenerate with |', '|---|---|---|');
    for (const r of problems) lines.push(`| ${r.entry.pack}/${r.entry.file} | ${r.failure ?? ''} | ${r.entry.promptFile} |`);
  }

  const warned = results.filter((r) => r.warnings.length > 0);
  lines.push('', '## 3. Cut, but look at these in the gallery', '');
  if (warned.length === 0) lines.push('No automatic warnings.');
  else for (const r of warned) for (const warning of r.warnings) lines.push(`- \`${r.entry.file}\`: ${warning}`);

  lines.push('', '## 4. Every file', '');
  for (const listing of listings) {
    lines.push(`### ${listing.pack}`, '', '| File | Pieces | How it was cut | Scale | Final size |', '|---|---|---|---|---|');
    for (const r of results.filter((x) => x.entry.pack === listing.pack)) {
      const pieces = r.status === 'reference' ? 'reference' : `${r.got}/${r.expected} ${tick(r.got === r.expected)}`;
      const scale = r.scale === null ? '-' : r.scale.toFixed(2);
      lines.push(`| ${r.entry.file} | ${pieces} | ${r.method} | ${scale} | ${r.entry.finalSizeText} |`);
    }
    lines.push('');
  }

  if (existsSync(notesPath)) lines.push(readFileSync(notesPath, 'utf8').trim(), '');
  return lines.join('\n');
}
