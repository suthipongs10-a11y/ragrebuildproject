// Builds src/plantips.js: for every player style against every opponent style, how many win-rate points each
// plan option adds over a balanced plan at equal stats. The game's corner advice reads this table.
// Usage: node tools/plantips.mjs [fightsPerCell=300]     (rerun after any change to sim.js or data.js)
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
const N = process.argv[2] || '300', out = {};
for (const me of ['puncher', 'kicker', 'clinch', 'tech']) {
  const rows = JSON.parse(execFileSync('node', ['tools/plans.mjs', N, '--json'], {env: Object.assign({}, process.env, {ME: me})}).toString());
  out[me] = {};
  for (const [k, row] of Object.entries(rows)) { const o = {}; for (const [f, v] of Object.entries(row)) o[f] = +v; out[me][k] = o; }
  console.log(me, 'done');
}
writeFileSync('src/plantips.js', '// Generated by tools/plantips.mjs from mass simulation. Do not edit by hand.\n// PLAN_TIPS[myStyle]["vs <opponent style name>"]["ag:attack" | "rg:in" | "tg:leg" | ...] = win-rate points over a balanced plan; base = win rate with the balanced plan.\nexport const PLAN_TIPS = ' + JSON.stringify(out) + ';\n');
